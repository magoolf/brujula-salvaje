#!/usr/bin/env node
// Genera src/styles/tokens.css desde docs/03_diseno/tokens.json (W3C Design Tokens).
// Convención (HANDOFF_UI_UX DESIGN_SYSTEM.Convencion_CSS): --bs-<ruta-con-guiones>, sin "core"
// en los semánticos. Los tokens core se emiten como --bs-color-core-* solo para resolver alias.
// Uso: `npm run tokens:generate` (el CI puede comprobar `git diff --exit-code src/styles`).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const raiz = dirname(fileURLToPath(import.meta.url));
const origen = resolve(raiz, '../docs/03_diseno/tokens.json');
const destino = resolve(raiz, 'src/styles/tokens.css');
const tokens = JSON.parse(readFileSync(origen, 'utf8'));

const nombreVar = (ruta) => `--bs-${ruta.join('-')}`;

function resolverAlias(valor) {
  if (typeof valor !== 'string') return valor;
  return valor.replace(/\{([^}]+)\}/g, (_, ref) => `var(${nombreVar(ref.split('.'))})`);
}

function formatear(token, tipo) {
  const css = token.$extensions?.css;
  const v = token.$value;
  if (css?.value !== undefined) return css.value;
  switch (tipo) {
    case 'fontFamily':
      return v.map((f) => (/\s/.test(f) ? `'${f}'` : f)).join(', ');
    case 'shadow':
      return `${v.offsetX} ${v.offsetY} ${v.blur} ${v.spread} ${v.color}`;
    case 'cubicBezier':
      return `cubic-bezier(${v.join(', ')})`;
    case 'typography':
      return null; // se descompone en propiedades sueltas
    default:
      return resolverAlias(String(v));
  }
}

const lineas = [];
function recorrer(nodo, ruta, tipoHeredado) {
  const tipo = nodo.$type ?? tipoHeredado;
  if (nodo.$value !== undefined) {
    if (tipo === 'typography') {
      const v = nodo.$value;
      const base = nombreVar(ruta);
      const tam = nodo.$extensions?.css?.fontSize ?? v.fontSize;
      lineas.push(`  ${base}-font-family: ${resolverAlias(v.fontFamily)};`);
      lineas.push(`  ${base}-font-size: ${tam};`);
      lineas.push(`  ${base}-font-weight: ${v.fontWeight};`);
      lineas.push(`  ${base}-line-height: ${v.lineHeight};`);
      lineas.push(`  ${base}-letter-spacing: ${v.letterSpacing};`);
      return;
    }
    lineas.push(`  ${nombreVar(ruta)}: ${formatear(nodo, tipo)};`);
    return;
  }
  for (const [clave, hijo] of Object.entries(nodo)) {
    if (clave.startsWith('$') || typeof hijo !== 'object' || hijo === null) continue;
    recorrer(hijo, [...ruta, clave], tipo);
  }
}
recorrer(tokens, [], undefined);

const salida = `/* Code generated by generate-tokens.mjs from docs/03_diseno/tokens.json. DO NOT EDIT. */
:root {
${lineas.join('\n')}
}
`;
writeFileSync(destino, salida.replace(/\r\n/g, '\n'));
console.log(`tokens.css: ${lineas.length} variables`);
